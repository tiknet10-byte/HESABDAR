const pathOf = (pathname: string) => (pathname === "/" ? "/" : "/" + pathname.split("/")[1]);
const seenKey = (p: string) => `hesabdar:guide-seen:${p}`;

/** «راهنما» button for the header: opens the guide of the page you are on; a dot shows on pages not yet visited. */
export function GuideButton() {
  const loc = useLocation();
  const path = pathOf(loc.pathname);
  const [open, setOpen] = useState(false);
  const [which, setWhich] = useState(path);
  const [fresh, setFresh] = useState(false);
  useEffect(() => {
    setWhich(path);
    try { setFresh(!!GUIDES[path] && !localStorage.getItem(seenKey(path))); } catch { setFresh(false); }
  }, [path]);
  if (!GUIDES[path]) return null;
  const show = () => {
    setWhich(path);
    setOpen(true);
    setFresh(false);
    try { localStorage.setItem(seenKey(path), "1"); } catch { /* storage unavailable */ }
  };
  return (
    <>
      <button className="btn btn-ghost btn-sm relative" onClick={show} title="راهنمای ساده‌ی همین صفحه">
        <HelpCircle size={18} /><span className="hidden sm:inline">راهنما</span>
        {fresh && <span className="absolute -top-0.5 -right-0.5 h-2.5 w-2.5 animate-pulse rounded-full bg-amber-500" />}
      </button>
      <Modal open={open} onClose={() => setOpen(false)} title={`راهنما: ${GUIDES[which]?.title ?? ""}`}>
        {open && <GuideBody path={which} onPick={setWhich} />}
      </Modal>
    </>
  );
}

function GuideBody({ path, onPick }: { path: string; onPick: (p: string) => void }) {
  const g = GUIDES[path];
  const [openTask, setOpenTask] = useState<number | null>(0);
  useEffect(() => setOpenTask(0), [path]);
  return (
    <div className="space-y-4 text-sm leading-7">
      <p className="rounded-2xl bg-violet-500/10 p-3">{g.intro}</p>
      <div className="space-y-2">
        <div className="font-bold">چه کاری می‌خواهید انجام دهید؟</div>
        {g.tasks.map((t, i) => (
          <div key={t.q} className="overflow-hidden rounded-2xl border" style={{ borderColor: "var(--border)" }}>
            <button className="flex w-full items-center justify-between gap-2 px-3 py-2.5 text-right font-semibold hover:bg-violet-500/5" onClick={() => setOpenTask(openTask === i ? null : i)}>
              {t.q}<ChevronDown size={16} className={`shrink-0 transition ${openTask === i ? "rotate-180" : ""}`} />
            </button>
            {openTask === i && (
              <ol className="space-y-1.5 px-3 pb-3">
                {t.steps.map((s, j) => (
                  <li key={j} className="flex gap-2">
                    <span className="num grid h-6 w-6 shrink-0 place-items-center rounded-full bg-violet-600 text-xs font-bold text-white">{(j + 1).toLocaleString("fa-IR")}</span>
                    <span>{s}</span>
                  </li>
                ))}
              </ol>
            )}
          </div>
        ))}
      </div>
      {g.tips?.length ? (
        <div className="space-y-1 rounded-2xl bg-amber-500/10 p-3">
          <div className="flex items-center gap-1.5 font-bold"><Lightbulb size={16} className="text-amber-500" />نکته‌ها</div>
          <ul className="list-disc space-y-1 pr-5">{g.tips.map((t) => <li key={t}>{t}</li>)}</ul>
        </div>
      ) : null}
      <details className="rounded-2xl border p-3" style={{ borderColor: "var(--border)" }}>
        <summary className="cursor-pointer font-bold">معنی چند کلمه</summary>
        <dl className="mt-2 space-y-1">{GLOSSARY.map(([w, m]) => <div key={w}><dt className="inline font-bold">{w}: </dt><dd className="inline">{m}</dd></div>)}</dl>
      </details>
      <div>
        <div className="mb-1.5 flex items-center gap-1.5 font-bold"><BookOpen size={15} />راهنمای بخش‌های دیگر</div>
        <div className="flex flex-wrap gap-1.5">
          {Object.entries(GUIDES).filter(([p]) => p !== path).map(([p, x]) => (
            <button key={p} className="rounded-xl border px-2.5 py-1 text-xs font-semibold hover:bg-violet-500/10" style={{ borderColor: "var(--border)" }} onClick={() => onPick(p)}>{x.title}</button>
          ))}
        </div>
      </div>
    </div>
  );
}
